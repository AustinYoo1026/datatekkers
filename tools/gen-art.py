#!/usr/bin/env python3
"""Hand-authored flat-vector card art (bokeh backdrop + faceted, outlined figure) for the
online card and the nine drill cards. Each figure has its own bespoke polygons.
Usage: python3 tools/gen-art.py [out_dir]   (default: ../assets)"""
import random, os, sys

O = "#1f2433"; SW = 3.5
OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "assets")


def _p(pts):
    return " ".join(f"{round(x, 1):g},{round(y, 1):g}" for x, y in pts)

def P(pts, fill, st=True, op=None, sw=SW, extra=""):
    s = f' stroke="{O}" stroke-width="{sw}" stroke-linejoin="round"' if st else ""
    o = f' opacity="{op}"' if op is not None else ""
    return f'<polygon points="{_p(pts)}" fill="{fill}"{s}{o}{extra}/>'

def L(pts, col=O, w=SW, op=None, dash=None):
    o = f' opacity="{op}"' if op is not None else ""
    d = f' stroke-dasharray="{dash}"' if dash else ""
    return f'<polyline points="{_p(pts)}" fill="none" stroke="{col}" stroke-width="{w}" stroke-linecap="round" stroke-linejoin="round"{o}{d}/>'

def limb(pts, w, fill):
    return L(pts, O, w + 7) + L(pts, fill, w)

def E(cx, cy, rx, ry, fill, op=None, rot=None):
    o = f' opacity="{op}"' if op is not None else ""
    t = f' transform="rotate({rot} {cx} {cy})"' if rot else ""
    return f'<ellipse cx="{cx}" cy="{cy}" rx="{rx}" ry="{ry}" fill="{fill}"{o}{t}/>'

def G(inner, tf=None, extra=""):
    t = f' transform="{tf}"' if tf else ""
    return f'<g{t}{extra}>{inner}</g>'

def M(pts, dy=0):
    return [(600 - x, y + dy) for x, y in pts]

def eye(cx, cy, rx=13, ry=6.5, look=0, iris="#1c1512", white="#f6eee6", lid=True, lw=3.5, drop=0):
    r = min(ry * 0.98, 6.5)
    s = E(cx, cy, rx, ry, white) + f'<circle cx="{cx + look}" cy="{cy + drop}" r="{r:g}" fill="{iris}"/>'
    s += f'<circle cx="{cx + look + 2}" cy="{cy + drop - 2}" r="1.7" fill="#fff"/>'
    if lid:
        s += L([(cx - rx - 1, cy - 1), (cx, cy - ry - 1.5), (cx + rx + 1, cy - 1)], O, lw)
    return s

def text(s, x, y, size, fill, rot=0, ls=0, sw=4):
    t = f' transform="rotate({rot} {x} {y})"' if rot else ""
    return (f'<text x="{x}" y="{y}" font-size="{size}" letter-spacing="{ls}" font-family="Arial Black, Arial, Helvetica, sans-serif" '
            f'font-weight="900" text-anchor="middle" fill="{fill}" stroke="{O}" paint-order="stroke" stroke-width="{sw}"{t}>{s}</text>')

def backdrop(seed, cols, bg0, bg1, band="#ffffff", n=120):
    r = random.Random(seed)
    c = "".join(f'<circle cx="{r.randint(-10, 610)}" cy="{r.randint(0, 830)}" r="{r.randint(11, 34)}" fill="{r.choice(cols)}" opacity="{r.uniform(.3, .8):.2f}"/>' for _ in range(n))
    return ('<defs><filter id="blur" x="-20%" y="-20%" width="140%" height="140%"><feGaussianBlur stdDeviation="9"/></filter>'
            '<filter id="blur2" x="-20%" y="-20%" width="140%" height="140%"><feGaussianBlur stdDeviation="5"/></filter>'
            '<pattern id="hatch" width="9" height="9" patternUnits="userSpaceOnUse" patternTransform="rotate(45)"><rect width="2.2" height="9" fill="#ffffff"/></pattern>'
            f'<pattern id="hatchd" width="9" height="9" patternUnits="userSpaceOnUse" patternTransform="rotate(45)"><rect width="2.2" height="9" fill="{O}"/></pattern>'
            f'<radialGradient id="g1" cx="50%" cy="35%" r="75%"><stop offset="0" stop-color="{bg0}"/><stop offset="1" stop-color="{bg1}"/></radialGradient></defs>'
            f'<rect width="600" height="830" fill="url(#g1)"/><g filter="url(#blur)">{c}</g>'
            f'<polygon points="0,90 600,10 600,120 0,220" fill="{band}" opacity=".07"/><polygon points="0,380 600,300 600,330 0,410" fill="{band}" opacity=".10"/>')

def svg(body):
    return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 600 830" width="600" height="830">{body}</svg>\n'


# Each figure is traced over its reference photograph: polygons are written in the photo's pixel coordinates and
# mapped onto the 600x830 card by fit(), so proportions, pose and features follow the reference.
def fit(k, cx, dy=0):
    return lambda pts: [((x - cx) * k + 300, y * k + dy) for x, y in pts]

class Tr:
    def __init__(self, k, cx, dy=0):
        self.k = k; self.f = fit(k, cx, dy)
    def P(self, pts, fill, st=True, op=None, sw=SW): return P(self.f(pts), fill, st, op, sw)
    def L(self, pts, col=O, w=SW, op=None): return L(self.f(pts), col, w, op)
    def limb(self, pts, w, fill): return limb(self.f(pts), w * self.k, fill)
    def pt(self, x, y): return self.f([(x, y)])[0]
    def eye(self, cx, cy, rx, ry, iris, look=0, white="#f3ece4"):
        a = [(cx - rx, cy + ry * .15), (cx - rx * .35, cy - ry), (cx + rx * .45, cy - ry * .95), (cx + rx, cy - ry * .05), (cx + rx * .35, cy + ry * .9), (cx - rx * .5, cy + ry * .85)]
        ix, iy = self.pt(cx + look, cy - ry * .05)
        s = P(self.f(a), white, False) + f'<circle cx="{ix:.1f}" cy="{iy:.1f}" r="{ry * .92 * self.k:.1f}" fill="{iris}"/>'
        s += f'<circle cx="{ix:.1f}" cy="{iy:.1f}" r="{ry * .42 * self.k:.1f}" fill="#14100e"/>'
        return s + L(self.f(a[:4]), O, 3.2)


